    public const COUNT = 44;

    public function run(): void
    {
        DemoData::seed(2002);
        $categories = Category::pluck('id', 'slug');
        if ($categories->isEmpty()) {
            $this->call(CategorySeeder::class);
            $categories = Category::pluck('id', 'slug');
        }

        $centers = DemoData::centerNames();
        for ($i = 1; $i <= self::COUNT; $i++) {
            [$cat, $title, $lead] = self::TEMPLATES[($i - 1) % count(self::TEMPLATES)];
            $center = $centers[($i * 5) % count($centers)];
            $village = DemoData::pick(DemoData::VILLAGES[$center]);
            $replace = fn (string $s) => str_replace(['{c}', '{v}'], [$center, $village], $s);
            $body = '<p>' . $replace($lead) . '</p>';
            foreach ((array) array_rand(array_flip(self::BODY), 3) as $p) {
                $body .= '<p>' . $p . '</p>';
            }
            $published = now()->subDays($i * 3 + mt_rand(0, 2));

            Post::updateOrCreate(['slug' => sprintf('kfs-demo-%02d', $i)], [
                'category_id' => $categories[$cat] ?? $categories->first(),
                'title' => $replace($title),
                'thumbnail' => DemoData::image('posts', 'post-' . $i),
                'content' => $body,
                'is_featured' => in_array($i, [1, 3, 6], true),
                'is_published' => $i % 15 !== 0, // بعض المسودات
                'published_at' => $published->toDateString(),
                'allow_comments' => true,
                'likes_count' => mt_rand(5, 450),
                'shares_count' => mt_rand(0, 120),
                'created_at' => $published,
            ]);
        }

        $this->seedComments();
    }

    private function seedComments(): void
    {
        if (Comment::count() >= 60) {
            return;
        }
        $texts = ['جهود مشكورة، ربنا يوفقكم.', 'نتمنى تعميم التجربة على باقي القرى.', 'متى يبدأ التنفيذ في قريتنا؟', 'خطوة ممتازة لخدمة الأهالي.',
            'برجاء الاهتمام بالطريق المؤدي للقرية.', 'شكراً للسيد المحافظ على المتابعة المستمرة.', 'هل الخدمة متاحة إلكترونياً بالكامل؟', 'تحية لكل العاملين بالمحافظة.'];
        $citizens = User::where('email', 'like', 'citizen%@demo.kfs.invalid')->pluck('id')->all();
        foreach (Post::where('slug', 'like', 'kfs-demo-%')->get() as $post) {
            for ($k = 0; $k < mt_rand(1, 3); $k++) {
                $female = DemoData::chance(40);
                Comment::create([
                    'post_id' => $post->id,
                    'user_id' => $citizens && DemoData::chance(60) ? DemoData::pick($citizens) : null,
                    'author_name' => DemoData::name($female),
                    'author_email' => 'reader' . mt_rand(100, 999) . '@example.com',
                    'content' => DemoData::pick($texts),
                    'is_approved' => DemoData::chance(80),
                ]);
            }
        }
    }
