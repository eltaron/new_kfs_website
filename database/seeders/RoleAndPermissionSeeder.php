    private static function matches(string $permission, array $patterns): bool
    {
        foreach ($patterns as $p) {
            if ($p === '*' || $permission === $p) {
                return true;
            }
            if (in_array($p, ['view_', 'view_any_'], true)) {
                if (str_starts_with($permission, $p) && ! str_starts_with($permission, 'view_any_') === ($p === 'view_')) {
                    return true;
                }
                continue;
            }
            if (! str_starts_with($p, 'page_') && ! str_starts_with($p, 'widget_')
                && preg_match('/^[a-z_]+_' . preg_quote($p, '/') . '$/', $permission)) {
                return true;
            }
        }

        return false;
    }
